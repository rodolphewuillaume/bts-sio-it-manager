CREATE TABLE SITES(
    CODE_SITE INT NOT NULL,
    NOM_SITE VARCHAR(50),
    VILLE VARCHAR(50),
    ADRESSE VARCHAR(100),
    PRIMARY KEY(CODE_SITE)
);

CREATE TABLE SERVICES(
    CODE_SERVICE INT NOT NULL,
    NOM_SERVICE VARCHAR(50),
    BUDGET_ANNUEL FLOAT,
    PRIMARY KEY(CODE_SERVICE)
);

CREATE TABLE FOURNISSEURS(
    ID_FOURNISSEUR INT NOT NULL,
    RAISON_SOCIALE VARCHAR(50),
    EMAIL VARCHAR(50),
    TELEPHONE VARCHAR(20),
    DELAI_LIVRAISON_JOURS INT,
    PRIMARY KEY(ID_FOURNISSEUR)
);

CREATE TABLE CATEGORIES(
    ID_CATEGORIE INT NOT NULL,
    LIBELLE VARCHAR(50),
    DUREE_AMORTISSEMENT_MOIS INT,
    PRIMARY KEY(ID_CATEGORIE)
);

CREATE TABLE LOGICIELS(
    ID_LOGICIEL INT NOT NULL,
    NOM_LOGICIEL VARCHAR(50),
    EDITEUR VARCHAR(50),
    VERSION VARCHAR(20),
    TYPE_LICENCE VARCHAR(20),
    PRIMARY KEY(ID_LOGICIEL),
);

CREATE TABLE COLLABORATEURS(
    MATRICULE INT NOT NULL,
    NOM VARCHAR(50),
    PRENOM VARCHAR(50),
    EMAIL_PRO VARCHAR(50),
    TELEPHONE_PRO VARCHAR(20),
    DATE_EMBAUCHE DATE,
    CODE_SERVICE INT,
    CODE_SITE INT,
    PRIMARY KEY(MATRICULE),
    FOREIGN KEY(CODE_SERVICE) REFERENCES SERVICES(CODE_SERVICE),
    FOREIGN KEY(CODE_SITE) REFERENCES SITES(CODE_SITE)
);

CREATE TABLE EQUIPEMENTS(
    NUM_SERIE INT NOT NULL,
    MARQUE VARCHAR(50),
    MODELE VARCHAR(50),
    DATE_ACHAT DATE,
    PRIX_ACHAT_HT FLOAT,
    DATE_FIN_GARANTIE DATE,
    ETAT VARCHAR(20),
    PRIX FLOAT,
    ID_CATEGORIE INT,
    ID_FOURNISSEUR INT,
    ID_LOGICIEL INT,
    PRIMARY KEY(NUM_SERIE),
    FOREIGN KEY(ID_CATEGORIE) REFERENCES CATEGORIES(ID_CATEGORIE),
    FOREIGN KEY(ID_FOURNISSEUR) REFERENCES FOURNISSEURS(ID_FOURNISSEUR),
    FOREIGN KEY(ID_LOGICIEL) REFERENCES LOGICIELS(ID_LOGICIEL)
);

CREATE TABLE TICKETS(
    NUM_TICKET INT NOT NULL,
    DATE_OUVERTURE DATE,
    DESCRIPTION_PANNE VARCHAR(250),
    NIVEAU_URGENCE VARCHAR(20),
    STATUT VARCHAR(20),
    NUM_SERIE INT,
    PRIMARY KEY(NUM_TICKET)
    FOREIGN KEY(NUM_SERIE) REFERENCES EQUIPEMENTS(NUM_SERIE)
);